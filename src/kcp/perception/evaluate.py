"""Evaluate every run-2 configuration on T1 (new people) and T2 (new people + unseen camera ID).

The selected model is the configuration with the best validation macro-F1; the test splits play
no part in that choice. All configurations are reported so the selection is visible."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import numpy as np
from sklearn.metrics import confusion_matrix, precision_recall_fscore_support

from kcp.perception.data import HELDOUT_CAMERA, Split
from kcp.perception.labels import CLASSES
from kcp.perception.train import (
    CONFIGS,
    TrainConfig,
    load_model,
    load_split,
    macro_f1,
    predict,
    prepare,
)

SPLITS: tuple[Split, ...] = ("T1", "T2")
LABELS = list(range(len(CLASSES)))
BASELINE = "frame_linear"


def metrics(y: np.ndarray, pred: np.ndarray) -> dict[str, Any]:
    p, r, f, support = precision_recall_fscore_support(y, pred, labels=LABELS, zero_division=0)
    return {
        "macro_f1": macro_f1(y, pred),
        "accuracy": float((y == pred).mean()),
        "per_class": {
            c: {
                "precision": float(p[i]),
                "recall": float(r[i]),
                "f1": float(f[i]),
                "support": int(support[i]),
            }
            for i, c in enumerate(CLASSES)
        },
        "confusion": confusion_matrix(y, pred, labels=LABELS).tolist(),
    }


def evaluate_all(cache_dir: Path, runs_dir: Path, reports_dir: Path) -> None:
    runs = {
        cfg.name: json.loads((runs_dir / cfg.name / "train.json").read_text()) for cfg in CONFIGS
    }
    selected = max(runs, key=lambda n: runs[n]["best_val_macro_f1"])
    results: dict[str, Any] = {
        "heldout_camera": HELDOUT_CAMERA,
        "selected": selected,
        "runs": runs,
        "splits": {},
    }
    train = load_split(cache_dir, "train")
    majority = int(np.argmax(np.bincount(train.y)))
    for split in SPLITS:
        raw = load_split(cache_dir, split)
        entry: dict[str, Any] = {
            "videos": len(raw.keys),
            "frames": int(len(raw.y)),
            "persons": sorted({k.split("_")[0] for k in raw.keys}),
            "models": {"majority_class": metrics(raw.y, np.full_like(raw.y, majority))},
        }
        for cfg in CONFIGS:
            model, cfg_loaded, mean, std = load_model(runs_dir / cfg.name)
            data = prepare(raw, cfg_loaded)
            entry["models"][cfg.name] = metrics(data.y, predict(model, data, mean, std))
        results["splits"][split] = entry
        summary = ", ".join(f"{m} {v['macro_f1']:.3f}" for m, v in entry["models"].items())
        print(f"{split} macro-F1: {summary}", flush=True)
    reports_dir.mkdir(parents=True, exist_ok=True)
    (reports_dir / "phase2a_metrics.json").write_text(json.dumps(results, indent=2) + "\n")
    (reports_dir / "phase2a_results.md").write_text(render(results))
    print(f"selected: {selected}; wrote {reports_dir / 'phase2a_results.md'}", flush=True)


def render(r: dict[str, Any]) -> str:
    sel = r["selected"]
    any_run = next(iter(r["runs"].values()))
    out = ["# Phase 2a — Run 2 Results (generated by `kcp-train evaluate`)", ""]
    out.append(
        f"Train: {any_run['train_videos']} videos, {any_run['train_frames']:,} frames (persons "
        f"s2–s3). Validation: {any_run['val_videos']} videos, {any_run['val_frames']:,} frames "
        f"(persons s4). Held-out camera ID: `{r['heldout_camera']}`."
    )
    for split, e in r["splits"].items():
        out.append(
            f"{split}: {e['videos']} videos, {e['frames']:,} frames, {len(e['persons'])} persons."
        )
    out += [
        "",
        f"Selected by validation macro-F1: **`{sel}`**.",
        "",
        "## Macro F1 (8 classes)",
        "",
        "| Model | Best epoch | Validation | T1: new people | T2: new people + unseen camera |",
        "|---|---:|---:|---:|---:|",
    ]
    t = [f"{r['splits'][s]['models']['majority_class']['macro_f1']:.3f}" for s in SPLITS]
    out.append(f"| `majority_class` | — | — | {' | '.join(t)} |")
    for name, run in r["runs"].items():
        t = [f"{r['splits'][s]['models'][name]['macro_f1']:.3f}" for s in SPLITS]
        mark = " (selected)" if name == sel else ""
        out.append(
            f"| `{name}`{mark} | {run['best_epoch']} | {run['best_val_macro_f1']:.3f} | "
            f"{' | '.join(t)} |"
        )
    for split in SPLITS:
        out += [
            "",
            f"## Per-class results — {split}, `{sel}` vs `{BASELINE}`",
            "",
            "| Class | Support | Precision | Recall | F1 | Baseline F1 |",
            "|---|---:|---:|---:|---:|---:|",
        ]
        pc = r["splits"][split]["models"][sel]["per_class"]
        base = r["splits"][split]["models"][BASELINE]["per_class"]
        for c in CLASSES:
            out.append(
                f"| `{c}` | {pc[c]['support']:,} | {pc[c]['precision']:.2f} | "
                f"{pc[c]['recall']:.2f} | {pc[c]['f1']:.2f} | {base[c]['f1']:.2f} |"
            )
        out += [
            "",
            f"Confusion matrix ({split}, `{sel}`; rows = true, columns = predicted):",
            "",
            "| true \\ pred | " + " | ".join(CLASSES) + " |",
            "|---|" + "---:|" * len(CLASSES),
        ]
        cm = r["splits"][split]["models"][sel]["confusion"]
        for c, row in zip(CLASSES, cm, strict=True):
            out.append(f"| `{c}` | " + " | ".join(f"{v:,}" for v in row) + " |")
    return "\n".join(out) + "\n"


def evaluate_2a2(
    cache_dir: Path,
    runs_dir: Path,
    reports_dir: Path,
    configs: tuple[TrainConfig, ...] | None = None,
    name: str = "phase2a2",
) -> None:
    """Planner-level evaluation of `configs` (default: Phase 2a.2). Selection: val macro-F1."""
    from kcp.perception.planner_metrics import CUT, MIX, binary_ap, event_score, tune_event
    from kcp.perception.train import CONFIGS_2A2, predict_proba

    configs = configs or CONFIGS_2A2
    results: dict[str, Any] = {"configs": {}}
    for features in dict.fromkeys(cfg.features for cfg in configs):
        raw = {s: load_split(cache_dir, s, features) for s in ("val", "T1", "T2")}
        for cfg in (c for c in configs if c.features == features):
            model, cfg_loaded, mean, std = load_model(runs_dir / cfg.name)
            data = {s: prepare(d, cfg_loaded) for s, d in raw.items()}
            probs = {s: predict_proba(model, d, mean, std) for s, d in data.items()}
            v = data["val"]
            width, threshold, val_event = tune_event(
                v.y, probs["val"][:, CUT[0]], v.frame, v.video_start
            )
            entry: dict[str, Any] = {
                "train": json.loads((runs_dir / cfg.name / "train.json").read_text()),
                "event_settings": {"width_s": width, "threshold": threshold},
                "splits": {},
            }
            for s, d in data.items():
                ev = event_score(d.y, probs[s][:, CUT[0]], d.frame, d.video_start, width, threshold)
                entry["splits"][s] = {
                    "steps": int(len(d.y)),
                    "videos": len(d.keys),
                    "macro_f1": macro_f1(d.y, probs[s].argmax(1)),
                    "cut_ap": binary_ap(d.y, probs[s], CUT),
                    "mix_ap": binary_ap(d.y, probs[s], MIX),
                    "cut_share": float(np.isin(d.y, CUT).mean()),
                    "mix_share": float(np.isin(d.y, MIX).mean()),
                    "cut_event": {"f1": ev.f1, "tp": ev.tp, "fp": ev.fp, "fn": ev.fn},
                }
            results["configs"][cfg.name] = entry
            t1, t2 = entry["splits"]["T1"], entry["splits"]["T2"]
            print(
                f"{cfg.name}: val F1 {entry['splits']['val']['macro_f1']:.3f} | "
                f"T1 F1 {t1['macro_f1']:.3f} cutAP {t1['cut_ap']:.3f} "
                f"ev {t1['cut_event']['f1']:.2f} | "
                f"T2 F1 {t2['macro_f1']:.3f} cutAP {t2['cut_ap']:.3f} "
                f"ev {t2['cut_event']['f1']:.2f}",
                flush=True,
            )
    results["selected"] = max(
        results["configs"], key=lambda n: results["configs"][n]["splits"]["val"]["macro_f1"]
    )
    reports_dir.mkdir(parents=True, exist_ok=True)
    (reports_dir / f"{name}_metrics.json").write_text(json.dumps(results, indent=2) + "\n")
    (reports_dir / f"{name}_results.md").write_text(render_2a2(results, name))
    print(f"selected: {results['selected']}", flush=True)


def render_2a2(r: dict[str, Any], name: str = "phase2a2") -> str:
    phase = name.removeprefix("phase")
    out = [
        f"# Phase {phase[0]}{phase[1:]} — Results (generated by `kcp-train evaluate-{phase}`)",
        "",
        f"Selected by validation macro-F1: **`{r['selected']}`**. Event settings (smoothing "
        "width, threshold) are chosen on validation for each model.",
        "",
        "## 8-class macro-F1",
        "",
        "| Model | Val | T1 | T2 |",
        "|---|---:|---:|---:|",
    ]
    for name, e in r["configs"].items():
        s = e["splits"]
        out.append(
            f"| `{name}` | {s['val']['macro_f1']:.3f} | {s['T1']['macro_f1']:.3f} | "
            f"{s['T2']['macro_f1']:.3f} |"
        )
    for split in ("T1", "T2"):
        first = next(iter(r["configs"].values()))["splits"][split]
        out += [
            "",
            f"## Planner metrics — {split}",
            "",
            f"Random-guess AP equals the class share: cutting {first['cut_share']:.3f}, "
            f"mixing {first['mix_share']:.3f} (mnv3 step grid; S3D steps are sparser).",
            "",
            "| Model | Cutting AP | Mixing AP | Cutting-event F1 | TP / FP / FN | Width, thr. |",
            "|---|---:|---:|---:|---|---|",
        ]
        for name, e in r["configs"].items():
            s = e["splits"][split]
            ev = s["cut_event"]
            es = e["event_settings"]
            out.append(
                f"| `{name}` | {s['cut_ap']:.3f} | {s['mix_ap']:.3f} | {ev['f1']:.2f} | "
                f"{ev['tp']} / {ev['fp']} / {ev['fn']} | {es['width_s']:.0f} s, {es['threshold']} |"
            )
    return "\n".join(out) + "\n"
